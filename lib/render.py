"""Terminal bars and the generated hardware.md block.

Colors are the startup header's muted truecolor palette
(share/fastfetch/mini.jsonc): percentiles go red / yellow / green.
"""
import os
import re

from percentile import ordinal
from sets import COMPONENT_LABELS, COMPONENTS

BEGIN = '<!-- hardware-bench:begin (generated by `hardware-bench report`; edits here are replaced) -->'
END = '<!-- hardware-bench:end -->'
FEW_SAMPLES = 100
POPULATION = ('Percentiles rank a result among OpenBenchmarking.org uploads for the same test and '
              'options, which lean to servers and workstations: a laptop ranks lower there than among PCs in general.')

RGB = {'green': (126, 166, 132), 'yellow': (196, 178, 118), 'red': (190, 112, 112),
       'dim': (100, 110, 125), 'text': (168, 176, 188), 'head': (122, 162, 200)}


def use_color(stream):
    return stream.isatty() and not os.environ.get('NO_COLOR')


class Paint:
    def __init__(self, on):
        self.on = on

    def __call__(self, name, text):
        if not self.on:
            return text
        r, g, b = RGB[name]
        return f'\x1b[38;2;{r};{g};{b}m{text}\x1b[m'


def tone(pct):
    if pct is None:
        return 'dim'
    return 'green' if pct >= 67 else 'yellow' if pct >= 34 else 'red'


def bar(pct, width=20):
    if pct is None:
        return '·' * width
    filled = round(pct * width / 100)
    return '█' * filled + '░' * (width - filled)


def number(v):
    if v is None:
        return '-'
    return f'{v:,.0f}' if abs(v) >= 100 else f'{v:,.2f}'


def data_note(t):
    notes = []
    if t.get('samples') is not None and t['samples'] < FEW_SAMPLES:
        notes.append(f"only {t['samples']} samples")
    if t.get('data_source') == 'bundled':
        notes.append(f"offline data to {t.get('data_last') or '?'}")
    return ', '.join(notes)


def by_component(tests):
    for c in COMPONENTS:
        rows = [t for t in tests if t['component'] == c]
        if rows:
            yield c, rows


# --- terminal ----------------------------------------------------------------
def terminal(rec, color=False, warnings=()):
    p = Paint(color)
    out = []
    sysinfo = rec.get('system', {})
    head = f"{rec['host']}  {rec['started'][:16].replace('T', ' ')}  {rec['set']} set, {rec['runs_per_test']} run(s) per test"
    out.append(p('head', head))
    if sysinfo:
        out.append(p('dim', '  ' + ' · '.join(sysinfo[k] for k in ('Processor', 'Memory', 'Graphics', 'Disk') if k in sysinfo)))
    for w in warnings:
        out.append(p('yellow', '  ! ' + w))
    label_w = max([len(t['label']) for t in rec['tests']] + [10])
    summary = rec.get('summary', {})
    for comp, rows in by_component(rec['tests']):
        pct = summary.get(comp)
        out.append('')
        out.append(f"{p('head', COMPONENT_LABELS[comp].ljust(label_w + 3))}"
                   f"{p(tone(pct), bar(pct))} {p(tone(pct), ordinal(pct).rjust(4))}")
        for t in rows:
            value = f"{number(t['value'])} {t.get('unit') or ''}".strip()
            note = data_note(t)
            line = (f"  {p('text', t['label'].ljust(label_w + 1))}{p(tone(t['percentile']), bar(t['percentile']))} "
                    f"{p(tone(t['percentile']), ordinal(t['percentile']).rjust(4))}  {p('text', value)}")
            samples = f"n={t['samples']:,}" if t.get('samples') else 'no data'
            out.append(line + '  ' + p('dim', samples + (f' ({note})' if note else '')))
    if 'overall' in summary:
        out.append('')
        pct = summary['overall']
        out.append(f"{p('head', 'Overall'.ljust(label_w + 3))}{p(tone(pct), bar(pct))} {p(tone(pct), ordinal(pct).rjust(4))}"
                   + p('dim', '  mean of the components'))
    pm = rec.get('passmark')
    if pm:
        out.append('')
        out.append(p('head', 'PassMark  ') + p('text', '  '.join(
            f'{k} {number(pm[v])}' for k, v in (('CPU Mark', 'cpu_mark'), ('Memory Mark', 'memory_mark'),
                                                 ('single thread', 'single_thread')) if pm.get(v) is not None)))
    for s in rec.get('skipped', []):
        out.append(p('dim', f"skipped {s['key']}: {s['reason']}"))
    out.append('')
    out.append(p('dim', POPULATION))
    retrieved = rec.get('data_retrieved')
    if retrieved:
        out.append(p('dim', f'Percentile data retrieved {retrieved[:10]}.'))
    return '\n'.join(out)


# --- markdown ----------------------------------------------------------------
def md_host(rec):
    out = [f"### {rec['host']}", '']
    sysinfo = rec.get('system', {})
    out.append(f"- Run {rec['started'][:16].replace('T', ' ')}, {rec['set']} set, {rec['runs_per_test']} run(s) per test; "
               f"percentile data retrieved {(rec.get('data_retrieved') or '?')[:10]}.")
    if sysinfo:
        out.append('- ' + ' · '.join(f'{k}: {sysinfo[k]}' for k in ('Processor', 'Memory', 'Graphics', 'Disk', 'OS') if k in sysinfo))
    warn = rec.get('warnings') or []
    if warn:
        out.append('- Conditions: ' + '; '.join(warn) + '.')
    out += ['', '| Component | Test | Result | Percentile | Samples |', '|---|---|---|---|---|']
    summary = rec.get('summary', {})
    for comp, rows in by_component(rec['tests']):
        for i, t in enumerate(rows):
            name = f"**{COMPONENT_LABELS[comp]}** ({ordinal(summary.get(comp))})" if i == 0 else ''
            value = f"{number(t['value'])} {t.get('unit') or ''}".strip()
            note = data_note(t)
            samples = (f"{t['samples']:,}" if t.get('samples') else '-') + (f' ({note})' if note else '')
            out.append(f"| {name} | {t['label']} | {value} | `{bar(t['percentile'], 10)}` {ordinal(t['percentile'])} | {samples} |")
    if 'overall' in summary:
        out.append(f"| **Overall** | mean of the components | | `{bar(summary['overall'], 10)}` {ordinal(summary['overall'])} | |")
    pm = rec.get('passmark')
    if pm:
        out += ['', 'PassMark: ' + ', '.join(
            f'{k} {number(pm[v])}' for k, v in (('CPU Mark', 'cpu_mark'), ('Memory Mark', 'memory_mark'),
                                                 ('single thread', 'single_thread')) if pm.get(v) is not None) + '.']
    skipped = rec.get('skipped') or []
    if skipped:
        out += ['', 'Skipped: ' + '; '.join(f"{s['key']} ({s['reason']})" for s in skipped) + '.']
    return '\n'.join(out)


def md_compare(recs):
    if len(recs) < 2:
        return ''
    head = '| | ' + ' | '.join(r['host'] for r in recs) + ' |'
    out = ['### Hosts compared', '', 'Percentile per component (latest run of each host).', '',
           head, '|---|' + '---|' * len(recs)]
    for comp in COMPONENTS + ('overall',):
        cells = [ordinal(r.get('summary', {}).get(comp)) for r in recs]
        if any(c != '-' for c in cells):
            out.append(f"| {COMPONENT_LABELS.get(comp, 'Overall')} | " + ' | '.join(cells) + ' |')
    for k, v in (('PassMark CPU Mark', 'cpu_mark'), ('PassMark Memory Mark', 'memory_mark')):
        cells = [number((r.get('passmark') or {}).get(v)) for r in recs]
        if any(c != '-' for c in cells):
            out.append(f'| {k} | ' + ' | '.join(cells) + ' |')
    return '\n'.join(out)


def md_block(recs):
    parts = [BEGIN, '', POPULATION, '']
    for r in recs:
        parts += [md_host(r), '']
    cmp = md_compare(recs)
    if cmp:
        parts += [cmp, '']
    parts.append(END)
    return '\n'.join(parts)


def update_notes(text, block):
    """Replace the generated block, else append it under its own heading."""
    pattern = re.compile(re.escape(BEGIN.split(' (')[0]) + r'.*?' + re.escape(END), re.S)
    if pattern.search(text):
        return pattern.sub(lambda _: block, text, count=1)
    return text.rstrip('\n') + '\n\n## Benchmarks (hardware-bench)\n\n`hardware-bench` runs these (quick set, `--full` for all);\n' \
        'each run is kept in `hardware/<host>/`.\n\n' + block + '\n'
